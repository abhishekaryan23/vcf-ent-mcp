"""
Enterprise Tool Catalogue and Semantic ToolCards.
Organized into three explicit levels:
- L1: Query tools (Read-only inventory, metrics, logs, health)
- L2: Operational tools (Power VM, resize, snapshot, segment creation)
- L3: Workflow tools (Domain upgrade, DR failover drill, host commissioning)

Includes parameter-level capability metadata (supported/unsupported parameters and actions)
and hard-negative rejection patterns to enforce safe deterministic routing and abstention.
"""

from __future__ import annotations
from typing import List, Dict, Any, Optional
from dataclasses import dataclass, field
from vcf_enterprise_mcp.policy.models import RiskClass, CapabilityRole


@dataclass
class EnterpriseToolCard:
    """Semantic descriptor defining access, triggers, risks, and hard-negatives for a tool."""
    name: str
    level: str  # "L1_QUERY", "L2_OPERATIONAL", "L3_WORKFLOW"
    risk_class: RiskClass
    required_roles: List[CapabilityRole]
    supported_versions: Dict[str, bool]
    description: str
    use_when: List[str]
    examples: List[str]
    domain: str = "compute"
    entity: List[str] = field(default_factory=list)
    actions: List[str] = field(default_factory=list)
    supported_parameters: List[str] = field(default_factory=list)
    unsupported_parameters: List[str] = field(default_factory=list)
    supported_actions: List[str] = field(default_factory=list)
    unsupported_actions: List[str] = field(default_factory=list)
    hard_negatives: List[str] = field(default_factory=list)
    schema: Dict[str, Any] = field(default_factory=dict)


