"""
A persistent Northwind lab for MCP clients you drive yourself (LM Studio, Claude Desktop, ...).

    python tools/org_sim/lab.py start [scenario]   # start (or restart) both lab personas
    python tools/org_sim/lab.py switch <scenario>  # change the injected fault, keep the client config
    python tools/org_sim/lab.py status
    python tools/org_sim/lab.py approve <persona> <plan_id> [--as someone@acme.lab]
    python tools/org_sim/lab.py stop
    python tools/org_sim/lab.py scenarios

Each persona lives in ~/.vcf-mcp-lab/<persona> (override with VCF_MCP_LAB_HOME) and has a
launcher, mcp-server.sh, that an MCP client runs as its stdio command. The launcher reads the
current token at start, so switching scenarios never requires editing the client config.

Personas: oncall (read-only VCF_VIEWER: troubleshooting) and automation (AUTOMATION_OPERATOR:
Assembler templates, Orchestrator actions/workflows/runs; changes need `lab.py approve`).
"""

from __future__ import annotations

import os
import shlex
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
HOME = Path(os.environ.get("VCF_MCP_LAB_HOME", Path.home() / ".vcf-mcp-lab"))
PY = str(REPO.parent / ".venv" / "bin" / "python") if (REPO.parent / ".venv" / "bin" / "python").exists() else sys.executable
PERSONAS = {"oncall": 7000, "automation": 7100}  # port offsets: oncall uses 16601-16641, automation 16701-16741


def _run(*args):
    return subprocess.run([PY, str(HERE / "run_scenario.py"), *args], check=True, stdout=subprocess.DEVNULL)


def launcher(state: Path) -> None:
    sys.path.insert(0, str(HERE))
    from run_scenario import server_env  # noqa: E402
    env = {k: v for k, v in server_env(state).items() if k.startswith(("VCF_", "PYTHON"))}
    lines = ["#!/bin/sh", "# Generated by tools/org_sim/lab.py: stdio launcher for the vcf-enterprise MCP server (lab persona).",
             f"cd {shlex.quote(str(REPO))} || exit 1"]
    lines += [f"export {k}={shlex.quote(v)}" for k, v in sorted(env.items())]
    lines += [f'VCF_MCP_AUTH_TOKEN="$(cat {shlex.quote(str(state / "viewer.token"))})"', "export VCF_MCP_AUTH_TOKEN",
              f'exec {shlex.quote(PY)} -c "from vcf_enterprise_mcp.core.server import main; main()"']
    path = state / "mcp-server.sh"
    path.write_text("\n".join(lines) + "\n")
    path.chmod(0o700)


def start(scenario: str = "orch_default") -> None:
    HOME.mkdir(parents=True, exist_ok=True, mode=0o700)
    for persona, offset in PERSONAS.items():
        state = HOME / persona
        if (state / "sim.pid").exists():
            _run("stop", str(state))
        _run("start", str(state), scenario, "--model", "enterprise", "--persona", persona, "--offset", str(offset))
        (state / "scenario").write_text(scenario)
        launcher(state)
    status()


def stop() -> None:
    for persona in PERSONAS:
        if (HOME / persona / "sim.pid").exists():
            _run("stop", str(HOME / persona))
    print("lab stopped")


def status() -> None:
    for persona in PERSONAS:
        state = HOME / persona
        pid = (state / "sim.pid").read_text().strip() if (state / "sim.pid").exists() else None
        alive = bool(pid) and subprocess.run(["kill", "-0", pid], capture_output=True).returncode == 0
        scen = (state / "scenario").read_text() if (state / "scenario").exists() else "-"
        print(f"{persona:11} {'running' if alive else 'stopped':8} scenario={scen:30} launcher={state / 'mcp-server.sh'}")


def scenarios() -> None:
    sys.path.insert(0, str(HERE))
    import enterprise_model
    for name in enterprise_model.SCENARIOS:
        print(name)


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else "status"
    if cmd == "start":
        start(sys.argv[2] if len(sys.argv) > 2 else "orch_default")
    elif cmd == "switch":
        start(sys.argv[2])
    elif cmd == "stop":
        stop()
    elif cmd == "scenarios":
        scenarios()
    elif cmd == "approve":
        persona, rest = sys.argv[2], sys.argv[3:]
        sys.exit(subprocess.call([str(HOME / persona / "vcf"), "approve", *rest]))
    else:
        status()
